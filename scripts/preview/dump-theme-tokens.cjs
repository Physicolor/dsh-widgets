/**
 * Dump the shell's semantic theme tokens into a standalone stylesheet.
 *
 * The offline card gallery (scripts/preview/gallery.mjs) renders the REAL card
 * components in a bare page, so it needs the REAL token values the shell hands
 * them (`--dsw-alias-*`, `--dsw-font-*`, `--dsw-shadow-*`, `--ds-transition-*`).
 * The definitions are injected at runtime by `dsh-client-ui-theme`, so they are
 * not in the published stylesheet — the only reliable source is a live page.
 *
 * Read-only against the GUI: signs in with a minted browser cookie, reads
 * `getComputedStyle(document.documentElement)` in both themes, writes
 * `docs/preview/theme-tokens.css`.
 *
 * Usage: node scripts/preview/dump-theme-tokens.cjs
 */
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(path.join('C:/Users/12404/AppData/Local/npm-cache/_npx/86170c4cd1c5da32/node_modules', 'playwright-core'))
const { chromePath } = require('../lib/chrome.cjs')
const { mintCookie } = require('../diag-auth-lib.cjs')

const ORIGIN = 'http://127.0.0.1:3080'
const AUTHORITY = ORIGIN.replace(/^https?:\/\//, '')
const ROOT = path.join(__dirname, '..', '..')
const OUT = path.join(ROOT, 'docs', 'preview', 'theme-tokens.css')

/** Every custom property the shell declares, read off the live document. */
const COLLECT = () => {
  const names = new Set()
  const walk = (rules) => {
    for (const rule of rules) {
      if (rule.cssRules) walk(rule.cssRules)
      const text = rule.cssText ?? ''
      for (const m of text.matchAll(/(--[\w-]+)\s*:/g)) names.add(m[1])
    }
  }
  for (const sheet of document.styleSheets) {
    try { walk(sheet.cssRules) } catch { /* cross-origin: skip */ }
  }
  // The design-platform block declares the semantic aliases on `BODY`
  // (`body{--dsw-static-…}`), NOT on `:root` — reading the root element alone
  // finds only the handful of layout vars the plugins publish there.
  const cs = getComputedStyle(document.body)
  for (const name of cs) if (name.startsWith('--')) names.add(name)
  const out = {}
  for (const name of names) {
    const value = cs.getPropertyValue(name).trim()
    if (value !== '') out[name] = value
  }
  return out
}

const block = (selector, tokens) =>
  `${selector}{${Object.entries(tokens).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `${k}:${v}`).join(';')}}`

async function main() {
  const browser = await chromium.launch({ executablePath: chromePath(), headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  await context.addCookies([mintCookie(AUTHORITY)])
  const page = await context.newPage()
  await page.goto(ORIGIN, { waitUntil: 'domcontentloaded' })
  await page.waitForTimeout(2500)

  const light = await page.evaluate(COLLECT)
  // The shell keys its theme off `body[data-ds-dark-theme]` (see the plugin guide
  // §2.1): flip it, let the tokens resolve, read again.
  await page.evaluate(() => { document.body.setAttribute('data-ds-dark-theme', '') })
  await page.waitForTimeout(400)
  const dark = await page.evaluate(COLLECT)
  await page.evaluate(() => { document.body.removeAttribute('data-ds-dark-theme') })

  await browser.close()

  const keeps = (o) => Object.fromEntries(Object.entries(o).filter(([k]) =>
    k.startsWith('--dsw-') || k.startsWith('--ds-') || k.startsWith('--dsx-')))
  const lightKept = keeps(light)
  const darkKept = keeps(dark)
  if (Object.keys(lightKept).length === 0) throw new Error('no tokens read — is the GUI running at ' + ORIGIN + '?')

  const header = `/* Generated by scripts/preview/dump-theme-tokens.cjs — do not edit by hand.\n * Source: the live shell at ${ORIGIN} (dsh-client-ui-theme injected tokens).\n * ${Object.keys(lightKept).length} light tokens · ${Object.keys(darkKept).length} dark tokens. */\n`
  const css = `${header}${block(':root', lightKept)}\n${block('body[data-ds-dark-theme]', darkKept)}\n`
  fs.mkdirSync(path.dirname(OUT), { recursive: true })
  fs.writeFileSync(OUT, css, 'utf8')
  console.log(`[dump-theme-tokens] wrote ${OUT} — ${Object.keys(lightKept).length} light / ${Object.keys(darkKept).length} dark`)
}

main().catch((error) => { console.error('[dump-theme-tokens]', error); process.exit(1) })
